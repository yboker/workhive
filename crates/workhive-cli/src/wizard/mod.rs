//! Interactive setup wizard for `workhive init`.
//!
//! Unified flow for both global and project initialization:
//! 1. Language selection
//! 2. Overwrite check (if config exists, ask to overwrite upfront)
//! 3. Runtime backend selection
//! 4. Dependency check (git and the selected backend)
//! 5. Pane layout and startup commands
//! 6. Summary
//!
//! The wizard asks at most three questions on a fresh run: language,
//! layout, and whether to modify default pane commands. The trusted-roots
//! decision happens at the first `workspace open` / `init` inside a project
//! directory instead of inside this wizard.

