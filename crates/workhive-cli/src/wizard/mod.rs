/// Configuration target currently being generated by the wizard.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum InitConfigTarget {
    Global,
    Project,
}

/// Input bundle for running the interactive init/config wizard.
pub struct WizardRunRequest<'a> {
    pub force: bool,
    pub config_exists: bool,
    pub config_path: &'a str,
    pub target: InitConfigTarget,
    pub backend: Option<RuntimeBackendId>,
    pub deps: &'a dyn DependencyPort,
    pub exec_checker: &'a dyn ExecutableAvailabilityPort,
    pub config_port: &'a dyn workhive_core::ports::ConfigPort,
    pub i18n: &'a StaticI18n,
    pub locale: Locale,
}

fn default_logging_config() -> LogConfig {
    LogConfig {
        console: Some(ConsoleLogConfig {
            enabled: Some(true),
            level: Some(LogLevel::Warn),
            format: Some(LogFormat::Compact),
        }),
        file: Some(FileLogConfig {
            enabled: Some(true),
            level: Some(LogLevel::Debug),
            format: Some(LogFormat::Compact),
            scope: Some(FileLogScope::Global),
            directory: None,
            base_name: Some("workhive.log".to_owned()),
            rotation: Some(LogRotation::SizeMb(10)),
            retention: Some(LogRetention::MaxFiles(7)),
        }),
    }
}

pub(super) fn step_feedback(i18n: &StaticI18n, locale: Locale, description: &str) {
    eprintln!(
        "{}",
        i18n.resolve_with_args(locale, k::INIT_STEP_COMPLETE, &[description])
    );
}

pub(super) fn bool_display(i18n: &StaticI18n, locale: Locale, value: bool) -> String {
    if value {
        i18n.resolve(locale, k::BOOL_YES)
    } else {
        i18n.resolve(locale, k::BOOL_NO)
    }
}

pub(super) fn confirm_with_transcript(
    i18n: &StaticI18n,
    locale: Locale,
    prompt: &str,
    default: bool,
) -> Result<bool, CliError> {
    let value = crate::ui::screens::confirm::run(prompt, default)?;
    eprintln!("  {} → {}", prompt, bool_display(i18n, locale, value));
    Ok(value)
}

